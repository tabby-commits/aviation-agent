#!/usr/bin/env python3
from __future__ import annotations

import argparse
import json
import math
import os
import sys
from datetime import datetime
from pathlib import Path
from typing import Any

import pandas as pd
from dotenv import load_dotenv
from langchain_openai import ChatOpenAI
from ragas import EvaluationDataset, evaluate
from ragas.llms import LangchainLLMWrapper

try:
    from ragas.metrics import ContextPrecision, ContextRecall, ContextRelevance
except ImportError:  # pragma: no cover - compatibility fallback
    from ragas.metrics.collections import ContextPrecision, ContextRecall, ContextRelevance


def parse_args() -> argparse.Namespace:
    script_dir = Path(__file__).resolve().parent
    evaluation_dir = script_dir.parent
    parser = argparse.ArgumentParser(
        description="Run retrieval-only RAGAS evaluation on a labeled retrieval export."
    )
    parser.add_argument(
        "--input",
        default=str(evaluation_dir / "artifacts" / "retrieval_export_eval.jsonl"),
        help="Labeled retrieval export JSONL generated by the backend.",
    )
    parser.add_argument(
        "--output-csv",
        default="",
        help="Optional path for the row-level CSV report.",
    )
    parser.add_argument(
        "--ks",
        default="1,3,5",
        help="Comma-separated cutoffs for deterministic retrieval metrics.",
    )
    parser.add_argument(
        "--model",
        default=os.getenv("OPENAI_MODEL", "gpt-4o-mini"),
        help="OpenAI-compatible model name for RAGAS metrics.",
    )
    parser.add_argument(
        "--temperature",
        type=float,
        default=float(os.getenv("OPENAI_TEMPERATURE", "0")),
        help="Sampling temperature for the evaluator LLM.",
    )
    return parser.parse_args()


def load_environment(env_path: Path) -> None:
    if env_path.exists():
        load_dotenv(env_path)


def parse_ks(raw_value: str) -> list[int]:
    ks = []
    for part in raw_value.split(","):
        stripped = part.strip()
        if not stripped:
            continue
        value = int(stripped)
        if value <= 0:
            raise ValueError("All ks must be > 0")
        ks.append(value)
    if not ks:
        raise ValueError("At least one k is required")
    return sorted(set(ks))


def read_jsonl(path: Path) -> list[dict[str, Any]]:
    if not path.exists():
        raise FileNotFoundError(f"Input file does not exist: {path}")
    rows: list[dict[str, Any]] = []
    with path.open("r", encoding="utf-8") as handle:
        for line_number, line in enumerate(handle, start=1):
            text = line.strip()
            if not text:
                continue
            try:
                rows.append(json.loads(text))
            except json.JSONDecodeError as exc:
                raise ValueError(f"Invalid JSONL at line {line_number}: {exc}") from exc
    return rows


def build_ragas_dataset(rows: list[dict[str, Any]]) -> tuple[EvaluationDataset, pd.DataFrame]:
    samples: list[dict[str, Any]] = []
    metadata_rows: list[dict[str, Any]] = []

    for row in rows:
        retrieved = row.get("retrieved", [])
        retrieved_contexts = [hit.get("content", "") for hit in retrieved if hit.get("content")]
        samples.append(
            {
                "user_input": row.get("user_input", ""),
                "reference": row.get("reference", ""),
                "retrieved_contexts": retrieved_contexts,
            }
        )
        metadata_rows.append(
            {
                "sample_id": row.get("sample_id"),
                "topic": row.get("topic"),
                "difficulty": row.get("difficulty"),
                "user_input": row.get("user_input"),
                "reference": row.get("reference"),
                "reference_context_ids": row.get("reference_context_ids", []),
                "retrieved_chunk_ids": [hit.get("chunk_id") for hit in retrieved if hit.get("chunk_id")],
            }
        )

    return EvaluationDataset.from_list(samples), pd.DataFrame(metadata_rows)


def dcg(binary_relevances: list[int]) -> float:
    score = 0.0
    for index, rel in enumerate(binary_relevances, start=1):
        if rel:
            score += rel / math.log2(index + 1)
    return score


def compute_deterministic_metrics(
    metadata_df: pd.DataFrame,
    ks: list[int],
) -> pd.DataFrame:
    rows: list[dict[str, Any]] = []
    for _, row in metadata_df.iterrows():
        retrieved_ids = row["retrieved_chunk_ids"] or []
        reference_ids = row["reference_context_ids"] or []
        reference_set = set(reference_ids)

        metric_row: dict[str, Any] = {}
        if not reference_set:
            for k in ks:
                metric_row[f"hit_rate_at_{k}"] = None
                metric_row[f"recall_at_{k}"] = None
                metric_row[f"ndcg_at_{k}"] = None
            metric_row["mrr"] = None
            rows.append(metric_row)
            continue

        first_relevant_rank = None
        for idx, chunk_id in enumerate(retrieved_ids, start=1):
            if chunk_id in reference_set:
                first_relevant_rank = idx
                break
        metric_row["mrr"] = 0.0 if first_relevant_rank is None else 1.0 / first_relevant_rank

        for k in ks:
            top_k = retrieved_ids[:k]
            hits = sum(1 for chunk_id in top_k if chunk_id in reference_set)
            metric_row[f"hit_rate_at_{k}"] = 1.0 if hits > 0 else 0.0
            metric_row[f"recall_at_{k}"] = hits / len(reference_set)

            binary_relevances = [1 if chunk_id in reference_set else 0 for chunk_id in top_k]
            actual_dcg = dcg(binary_relevances)
            ideal_binary = [1] * min(len(reference_set), k)
            ideal_dcg = dcg(ideal_binary)
            metric_row[f"ndcg_at_{k}"] = 0.0 if ideal_dcg == 0 else actual_dcg / ideal_dcg

        rows.append(metric_row)

    return pd.DataFrame(rows)


def make_evaluator_llm(model: str, temperature: float) -> LangchainLLMWrapper:
    api_key = os.getenv("OPENAI_API_KEY")
    if not api_key:
        raise RuntimeError("OPENAI_API_KEY is required. Create rag_eval/.env from .env.example first.")

    base_url = os.getenv("OPENAI_BASE_URL")
    chat_model = ChatOpenAI(
        model=model,
        api_key=api_key,
        base_url=base_url,
        temperature=temperature,
    )
    return LangchainLLMWrapper(chat_model)


def main() -> int:
    args = parse_args()
    evaluation_dir = Path(__file__).resolve().parent.parent
    load_environment(evaluation_dir / ".env")

    input_path = Path(args.input).resolve()
    ks = parse_ks(args.ks)
    run_name = datetime.now().strftime("%Y%m%d_%H%M%S")
    output_csv = Path(args.output_csv).resolve() if args.output_csv else (
        evaluation_dir / "reports" / f"ragas_scores_{run_name}.csv"
    )

    rows = read_jsonl(input_path)
    if not rows:
        print("The input retrieval export is empty.", file=sys.stderr)
        return 1

    ragas_dataset, metadata_df = build_ragas_dataset(rows)
    evaluator_llm = make_evaluator_llm(args.model, args.temperature)
    metrics = [
        ContextPrecision(llm=evaluator_llm),
        ContextRecall(llm=evaluator_llm),
        ContextRelevance(llm=evaluator_llm),
    ]

    evaluation_result = evaluate(dataset=ragas_dataset, metrics=metrics)
    ragas_df = evaluation_result.to_pandas().reset_index(drop=True)
    deterministic_df = compute_deterministic_metrics(metadata_df, ks).reset_index(drop=True)

    combined_df = pd.concat(
        [metadata_df.reset_index(drop=True), ragas_df.reset_index(drop=True), deterministic_df],
        axis=1,
    )
    output_csv.parent.mkdir(parents=True, exist_ok=True)
    combined_df.to_csv(output_csv, index=False)

    print(
        f"[done] rows={len(combined_df)} output={output_csv.as_posix()} "
        f"metrics={','.join(metric.__class__.__name__ for metric in metrics)}"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
